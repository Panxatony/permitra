const LangContext = createContext({ lang: 'de', t: (s) => s, toggle: () => {} })

export function LangProvider({ children }) {
  const [lang, setLang] = useState(localStorage.getItem('permitra_lang') || 'de')
  const t = (s) => (lang === 'de' ? s : (EN[s] ?? s))
  const toggle = () => {
    const next = lang === 'de' ? 'en' : 'de'
    setLang(next)
    localStorage.setItem('permitra_lang', next)
  }
  return <LangContext.Provider value={{ lang, t, toggle }}>{children}</LangContext.Provider>
}

export const useLang = () => useContext(LangContext)
