const LangContext = createContext({ lang: 'en', t: (s) => s })

/* The interface language is set by the administrator for the whole instance
   (setting `ui_language`), not per user. Until it has been loaded the English
   source text is shown, which is also the fallback for anything the dictionary
   does not cover - a missing translation then reads as English rather than as
   a key. */
export function LangProvider({ children, lang = 'en' }) {
  const t = (s) => (lang === 'de' ? (DE[s] ?? s) : s)
  return <LangContext.Provider value={{ lang, t }}>{children}</LangContext.Provider>
}

/* Dates follow the instance language too.

   A German instance showing "8/23/2026, 12:03:58 PM" is as wrong as an English
   one showing "23.8.2026" - and the second was what happened, because every
   call site had 'de-DE' written into it. The mapping lives here so there is one
   place to change when a third language arrives. */
export function dateLocale(lang) {
  return lang === 'de' ? 'de-DE' : 'en-GB'
}

/* Translate outside the React tree (used by api.js for backend messages). */
export function translate(text, lang) {
  return lang === 'de' ? (DE[text] ?? text) : text
}

export const useLang = () => useContext(LangContext)
